-- ---------- Request Type  ->  Unit Type ----------
BEGIN EXECUTE IMMEDIATE 'DROP TABLE RP_M_REQTYPE_UNITTYPE CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
CREATE TABLE RP_M_REQTYPE_UNITTYPE (
    ID              NUMBER(19) NOT NULL,
    REQUEST_TYPE_ID NUMBER(19) NOT NULL,
    UNIT_TYPE_ID    NUMBER(19) NOT NULL,
    CONSTRAINT PK_RP_RT_UT PRIMARY KEY (ID),
    CONSTRAINT UQ_RP_RT_UT UNIQUE (REQUEST_TYPE_ID, UNIT_TYPE_ID),
    CONSTRAINT FK_RP_RT_UT_RT FOREIGN KEY (REQUEST_TYPE_ID) REFERENCES RP_M_REQUEST_TYPE(ID),
    CONSTRAINT FK_RP_RT_UT_UT FOREIGN KEY (UNIT_TYPE_ID)    REFERENCES RP_M_UNIT_TYPE(ID)
);

