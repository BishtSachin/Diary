    ID          NUMBER(19) NOT NULL,
    UNIT_ID     NUMBER(19) NOT NULL,
    VERTICAL_ID NUMBER(19) NOT NULL,
    CONSTRAINT PK_RP_U_V PRIMARY KEY (ID),
    CONSTRAINT UQ_RP_U_V UNIQUE (UNIT_ID, VERTICAL_ID),
    CONSTRAINT FK_RP_U_V_U FOREIGN KEY (UNIT_ID)     REFERENCES RP_M_UNIT(ID),
    CONSTRAINT FK_RP_U_V_V FOREIGN KEY (VERTICAL_ID) REFERENCES RP_M_VERTICAL(ID)
);

